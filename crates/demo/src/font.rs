/// rows of the glyph for `c`, case-insensitive. unknown characters are blank.
pub fn glyph(c: char) -> [u8; 7] {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map_or([0; 7], |(_, rows)| *rows)
}

